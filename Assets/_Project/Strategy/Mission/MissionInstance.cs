using System;
using System.Collections.Generic;
using Apogee.Core.Simulation.Cruise;
using Apogee.Core.Simulation.Launch;
using Apogee.Core.Simulation.Operations;
using Apogee.Core.Simulation.Report;
using Apogee.Design;

namespace Apogee.Strategy.Mission
{
    /// <summary>
    /// Runtime instance of a campaign mission.
    /// Holds design reference, lifecycle status, accumulated cruise data, and pending decisions.
    /// All mutations occur through commands; this class is a pure data record.
    ///
    /// GDD §19.12 (Mission Instance schema), §10.1, §10.2, §6.2 (map progress marker).
    /// </summary>
    public sealed class MissionInstance
    {
        // ---------------------------------------------------------------- identity
        /// <summary>Unique mission ID within the campaign.</summary>
        public string MissionId { get; }

        /// <summary>Player-given mission name.</summary>
        public string MissionName { get; set; }

        /// <summary>Destination catalogue ID (e.g. "moon", "mars").</summary>
        public string DestinationId { get; }

        // ---------------------------------------------------------------- lifecycle
        /// <summary>Current lifecycle phase of this mission.</summary>
        public MissionStatus Status { get; set; }

        // ---------------------------------------------------------------- design
        /// <summary>
        /// The blueprint used for this mission.
        /// Snapshot is taken at launch; not the live active blueprint.
        /// </summary>
        public Blueprint Blueprint { get; }

        // ---------------------------------------------------------------- cruise progress (GDD §6.2 map marker)
        /// <summary>
        /// Cruise progress [0.0 – 1.0].
        /// 0 = just inserted into cruise orbit / transfer, 1 = destination reached.
        /// Used by the Solar System map to position the spacecraft marker.
        /// </summary>
        public double CruiseProgress { get; set; }

        /// <summary>Total planned cruise duration in game-days.</summary>
        public int CruiseDurationDays { get; }

        /// <summary>Accumulated reliability degradation from cruise events [0.0 – 1.0].</summary>
        public double AccumulatedReliabilityPenalty { get; set; }

        /// <summary>Accumulated correction-burn fuel fraction consumed during cruise.</summary>
        public double AccumulatedCorrectionFuel { get; set; }

        // ---------------------------------------------------------------- cruise events
        /// <summary>
        /// Segment events resolved so far (append-only log for cause-chain reporting).
        /// </summary>
        public List<CruiseSegmentEvent> CruiseEventLog { get; } = new List<CruiseSegmentEvent>();

        /// <summary>
        /// Decision cards that have been presented to the player and their resolved option IDs.
        /// Key = DecisionId, Value = chosen OptionId.
        /// </summary>
        public Dictionary<string, string> ResolvedDecisions { get; } =
            new Dictionary<string, string>(StringComparer.Ordinal);

        /// <summary>
        /// Decision card currently awaiting player input (null if none pending).
        /// Set by AdvanceCruiseCommand when a DecisionRequired segment is reached.
        /// Cleared by ResolveCruiseDecisionCommand.
        /// </summary>
        public CruiseDecisionCard PendingDecisionCard { get; set; }

        // ---------------------------------------------------------------- dates
        /// <summary>Game tick at which the launch was executed.</summary>
        public int LaunchTick { get; set; }

        /// <summary>Game tick at which the cruise phase started.</summary>
        public int CruiseStartTick { get; set; }

        // ---------------------------------------------------------------- seed
        /// <summary>Deterministic seed for this mission's simulation stream.</summary>
        public ulong MissionSeed { get; }

        // ---------------------------------------------------------------- edl results
        /// <summary>
        /// Resolved EDL simulation result if the mission attempted an entry/descent/landing.
        /// </summary>
        public Apogee.Core.Simulation.EDL.EdlSimulationResult EdlResult { get; set; }

        // ---------------------------------------------------------------- science operations results (M5-04)
        /// <summary>
        /// Total science data successfully downlinked to Earth so far in GB.
        /// GDD §8.1, §10.5, §11.1.
        /// </summary>
        public double AccumulatedDownlinkDataGb { get; set; }

        /// <summary>
        /// Total science data generated by instruments on-board so far in GB.
        /// </summary>
        public double AccumulatedRawDataGeneratedGb { get; set; }

        /// <summary>
        /// Total science data lost due to buffer overflows in GB.
        /// </summary>
        public double AccumulatedDroppedDataGb { get; set; }

        /// <summary>
        /// Current on-board storage buffer usage in GB.
        /// </summary>
        public double CurrentBufferStorageGb { get; set; }

        /// <summary>
        /// Current battery energy storage in kWh.
        /// </summary>
        public double CurrentBatteryStorageKwh { get; set; }

        /// <summary>
        /// Operational days spent in science phase.
        /// </summary>
        public int ScienceDaysCompleted { get; set; }

        /// <summary>
        /// Log of daily science results.
        /// </summary>
        public List<Apogee.Core.Simulation.Science.ScienceSimulationResult> ScienceLog { get; } =
            new List<Apogee.Core.Simulation.Science.ScienceSimulationResult>();

        // ---------------------------------------------------------------- operation events (M5-05)
        /// <summary>
        /// Currently pending operation event requiring player decision (null if none).
        /// Set by ResolveOperationEventCommand when an event fires.
        /// Cleared once the player selects an option.
        /// GDD §10.2.
        /// </summary>
        public ActiveOperationEvent PendingOperationEvent { get; set; }

        /// <summary>
        /// Log of all resolved operation events for this mission.
        /// Used for cause-chain reporting (GDD §10.5).
        /// </summary>
        public List<ActiveOperationEvent> OperationEventLog { get; } =
            new List<ActiveOperationEvent>();

        /// <summary>
        /// IDs of non-repeatable operation events that have already fired for this mission.
        /// </summary>
        public HashSet<string> UsedNonRepeatableOperationEvents { get; } =
            new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        // ---------------------------------------------------------------- launch & report results (M5-06)
        /// <summary>
        /// Resolved launch attempt result.
        /// </summary>
        public LaunchSimulationResult LaunchResult { get; set; }

        /// <summary>
        /// Associated mission profile (requirements and success criteria).
        /// </summary>
        public MissionProfile Profile { get; set; }

        /// <summary>
        /// Post-mission generated report (GDD §10.5, §19.12).
        /// </summary>
        public MissionReport Report { get; set; }

        // ---------------------------------------------------------------- construction
        public MissionInstance(
            string missionId,
            string missionName,
            string destinationId,
            Blueprint blueprint,
            int cruiseDurationDays,
            ulong missionSeed)
        {
            MissionId          = missionId ?? throw new ArgumentNullException(nameof(missionId));
            MissionName        = missionName ?? string.Empty;
            DestinationId      = destinationId ?? string.Empty;
            Blueprint          = blueprint;
            CruiseDurationDays = cruiseDurationDays < 1 ? 1 : cruiseDurationDays;
            MissionSeed        = missionSeed;
            Status             = MissionStatus.Planning;
        }

        public override string ToString() =>
            $"[Mission:{MissionId}] \"{MissionName}\"-> {DestinationId}, Status={Status}, Progress={CruiseProgress:P0}";
    }
}
