using System.Collections.Generic;
using Newtonsoft.Json;

namespace Apogee.Data
{
    /// <summary>
    /// JSON-serializable catalog record for a spacecraft/rocket module or component.
    /// Maps to GDD §19.4 (Module schema) and §16 catalog values.
    ///
    /// JSON key convention: camelCase (STANDARDS.md §1).
    /// All numeric values use SI units as noted; "TODO-VERİ" fields have placeholder 0.
    /// </summary>
    public sealed class ModuleRecord : ICatalogRecord
    {
        // ── Identity ─────────────────────────────────────────────────────────────

        /// <inheritdoc />
        [JsonProperty("id", Required = Required.Always)]
        public string Id { get; private set; }

        /// <summary>Localization key for the display name (STANDARDS.md §4).</summary>
        [JsonProperty("nameKey")]
        public string NameKey { get; private set; }

        /// <summary>Localization key for the description tooltip.</summary>
        [JsonProperty("descKey")]
        public string DescKey { get; private set; }

        /// <summary>Icon asset address (Addressables key or Resources path).</summary>
        [JsonProperty("icon")]
        public string Icon { get; private set; }

        /// <summary>
        /// Semantic category tag. GDD §19.4 examples:
        /// "payload", "bus", "engine", "tank", "structure", "power", "thermal",
        /// "comms", "adcs", "edl", "life-support", "cabin", "instrument".
        /// </summary>
        [JsonProperty("category")]
        public string Category { get; private set; }

        // ── Physical properties ───────────────────────────────────────────────────

        /// <summary>Dry structural mass in metric tons (t). GDD §8.1.</summary>
        [JsonProperty("dryMassTons")]
        public double DryMassTons { get; private set; }

        // ── Power ────────────────────────────────────────────────────────────────

        /// <summary>Power generated by this module in kilowatts (kW). Positive = producer.</summary>
        [JsonProperty("powerGenerationKw")]
        public double PowerGenerationKw { get; private set; }

        /// <summary>Power consumed by this module in kilowatts (kW). Positive = consumer.</summary>
        [JsonProperty("powerConsumptionKw")]
        public double PowerConsumptionKw { get; private set; }

        // ── Thermal ──────────────────────────────────────────────────────────────

        /// <summary>Internal heat generated + absorbed (kW).</summary>
        [JsonProperty("thermalLoadKw")]
        public double ThermalLoadKw { get; private set; }

        /// <summary>Radiator / insulation dissipation capacity (kW).</summary>
        [JsonProperty("thermalDissipationKw")]
        public double ThermalDissipationKw { get; private set; }

        // ── Data / Communications ────────────────────────────────────────────────

        /// <summary>Science data generation rate (GB/day) for instruments; 0 for non-instruments.</summary>
        [JsonProperty("dataRateGbPerDay")]
        public double DataRateGbPerDay { get; private set; }

        /// <summary>On-board data storage capacity (GB).</summary>
        [JsonProperty("dataStorageGb")]
        public double DataStorageGb { get; private set; }

        /// <summary>Ground downlink rate (GB/day); 0 for non-comms modules.</summary>
        [JsonProperty("downlinkRateGbPerDay")]
        public double DownlinkRateGbPerDay { get; private set; }

        // ── Cost &amp; schedule ────────────────────────────────────────────────────

        /// <summary>Base procurement/manufacturing cost in millions USD (M$). GDD §8.1.</summary>
        [JsonProperty("costMUSD")]
        public double CostMUSD { get; private set; }

        /// <summary>Manufacturing time in game-days. GDD §8.1 / §19.4.</summary>
        [JsonProperty("buildTimeDays")]
        public int BuildTimeDays { get; private set; }

        // ── Reliability ───────────────────────────────────────────────────────────

        /// <summary>
        /// Base reliability [0.0 – 1.0]. Combined multiplicatively across modules.
        /// GDD §8.1 "seri sistem olarak birleştirilir (zayıf halka baskın)".
        /// </summary>
        [JsonProperty("baseReliability")]
        public double BaseReliability { get; private set; }

        // ── Research gate ─────────────────────────────────────────────────────────

        /// <summary>
        /// Id of the research node that must be completed to unlock this module.
        /// Null or empty = available from campaign start.
        /// </summary>
        [JsonProperty("researchRequiredId")]
        public string ResearchRequiredId { get; private set; }

        // ── Slot compatibility ────────────────────────────────────────────────────

        /// <summary>
        /// Slot category tags this module can occupy in the Design Workshop.
        /// GDD §7.3 / §19.4 "uyumlu slot etiketleri".
        /// </summary>
        [JsonProperty("slotTags")]
        public List<string> SlotTags { get; private set; } = new List<string>();

        // ── Propulsion-specific (engines only) ────────────────────────────────────

        /// <summary>Specific impulse in seconds. Non-zero only for engine modules.</summary>
        [JsonProperty("isp")]
        public double Isp { get; private set; }

        /// <summary>Vacuum thrust in kilonewtons (kN). Non-zero only for engine modules.</summary>
        [JsonProperty("thrustVacKn")]
        public double ThrustVacKn { get; private set; }

        /// <summary>Propellant type tag, e.g. "kerosene-lox", "hydrogen-lox", "solid", "ion".</summary>
        [JsonProperty("propellantType")]
        public string PropellantType { get; private set; }

        // ── Instrument-specific ───────────────────────────────────────────────────

        /// <summary>Science value multiplier for scoring. GDD §11.1 / §16.5.</summary>
        [JsonProperty("scienceValue")]
        public double ScienceValue { get; private set; }

        /// <summary>Required instrument categories for mission objectives (instruments only).</summary>
        [JsonProperty("instrumentCategories")]
        public List<string> InstrumentCategories { get; private set; } = new List<string>();

        // ── Extra stat modifiers ───────────────────────────────────────────────────

        /// <summary>
        /// Free-form stat modifier list. Each entry is a key-value string pair:
        /// "statType:modifierType:value"  e.g. "Reliability:PercentAdd:0.05".
        /// Parsed by the Design layer; unknown entries are warned and skipped.
        /// GDD §19.4 "ek etkiler listesi".
        /// </summary>
        [JsonProperty("statModifiers")]
        public List<string> StatModifiers { get; private set; } = new List<string>();

        public override string ToString() => $"[{Category}] {Id}  dry={DryMassTons}t  cost={CostMUSD}M$";
    }
}
